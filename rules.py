# -*- coding: utf-8 -*-
"""
Правила типографского оформления юридических/градостроительных документов.
Каждое правило — функция text -> text. Порядок применения важен (см. RULES в конце).
"""
import re

NBSP = '\u00A0'   # неразрывный пробел
NBH = '\u2011'    # неразрывный дефис
ENDASH = '\u2013' # короткое тире
EMDASH = '\u2014' # длинное тире

LOG = []  # список (rule_name, start, end, old, new) — заполняется при прогоне с логированием


def _sub(pattern, repl, text, name, flags=0):
    """re.sub с логированием каждой замены (для dry-run отчёта)."""
    def _do(m):
        old = m.group(0)
        new = m.expand(repl) if isinstance(repl, str) else repl(m)
        if new != old:
            LOG.append((name, m.start(), old, new))
        return new
    return re.sub(pattern, _do, text, flags=flags)


# ---------------------------------------------------------------------------
# 1. Единицы измерения: унификация м²/м2/m3 -> "кв. м" / "куб. м"
# ---------------------------------------------------------------------------

# Верхний индекс 2/3 в Word — это ОБЫЧНАЯ цифра (реже юникод ²/³) в отдельном
# run'е с надстрочным форматированием; в тексте выглядит как "м2"/"м3". Иногда
# тройка набрана кириллической «З» (U+0417) — тоже учитываем. Приводим к тексту
# "кв.<nbsp>м"/"куб.<nbsp>м" ДАЖЕ без цифры слева (заголовки таблиц "Объём, м3").
# Защита от дм2/см2/мм2 и слов — lookbehind: перед "м" не должно быть буквы.
_M2 = r'(?<![А-Яа-яЁёA-Za-z])м[2²]\b'
_M3 = r'(?<![А-Яа-яЁёA-Za-z])м[3³З]\b'


def fix_unit_names(text):
    text = _sub(_M2, 'кв.' + NBSP + 'м', text, 'unit-m2->kvm')
    text = _sub(_M3, 'куб.' + NBSP + 'м', text, 'unit-m3->kubm')
    # уже словами (кв.м / кв. м / кв.<nbsp>м) -> канон с неразрывным пробелом
    text = _sub(r'кв\.[ \t ]?м\b', 'кв.' + NBSP + 'м', text, 'unit-kvm-normalize')
    text = _sub(r'куб\.[ \t ]?м\b', 'куб.' + NBSP + 'м', text, 'unit-kubm-normalize')
    return text


# ---------------------------------------------------------------------------
# 2. Неразрывные пробелы между числом и единицей измерения
# ---------------------------------------------------------------------------

# порядок важен: составные единицы (кв. м) — раньше одиночной "м".
# Канон после fix_unit_names — с неразрывным пробелом внутри ("кв.<nbsp>м").
UNITS_COMPOUND = [
    r'кв\.' + NBSP + r'м', r'куб\.' + NBSP + r'м',
]
UNITS_SIMPLE = [
    r'мм', r'см', r'км', r'га',
    r'л/с', r'кВт', r'кВА', r'кВ',
    r'Гкал/ч(?:ас)?', r'т/сут', r'тонн', r'прив\.\ ?ед\.', r'чел\.',
    r'руб\.', r'°C',
    r'м(?![а-яёА-ЯЁa-zA-Z])',  # "м" не часть другого слова/единицы
    r'%',
]

def fix_unit_spacing(text):
    for u in UNITS_COMPOUND:
        # "25 кв.<nbsp>м" -> "25<nbsp>кв.<nbsp>м" (внутренний nbsp уже есть)
        text = _sub(r'(\d)[ \t ]*(' + u + r')\b',
                     lambda m: m.group(1) + NBSP + m.group(2),
                     text, 'unit-compound-nbsp')
    for u in UNITS_SIMPLE:
        text = _sub(r'(\d)[ \t]*(' + u + r')',
                     lambda m: m.group(1) + NBSP + m.group(2),
                     text, 'unit-simple-nbsp')
    return text


# ---------------------------------------------------------------------------
# 3. "т.д.", "т.е.", "т.п.", "и др.", "в т.ч." — неразрывные пробелы внутри
# ---------------------------------------------------------------------------

def fix_common_abbrev(text):
    pairs = [
        (r'\bв\s?т\.\s?ч\.', 'в' + NBSP + 'т.' + NBSP + 'ч.'),
        (r'\bт\.\s?д\.', 'т.' + NBSP + 'д.'),
        (r'\bт\.\s?е\.', 'т.' + NBSP + 'е.'),
        (r'\bт\.\s?п\.', 'т.' + NBSP + 'п.'),
        (r'\bи\s?др\.', 'и' + NBSP + 'др.'),
    ]
    for pat, repl in pairs:
        text = _sub(pat, repl, text, 'common-abbrev')
    return text


# ---------------------------------------------------------------------------
# 4. № — неразрывный пробел после (перед числом) и перед (если есть текст слева)
# ---------------------------------------------------------------------------

def fix_number_sign(text):
    text = _sub(r'№[ \t]*(?=\d)', '№' + NBSP, text, 'numsign-after')
    # "№ исх." / "№ Вх" — неразрывный пробел между № и пометкой исходящий/входящий
    text = _sub(r'№[ \t]+(?=(?:исх|вх)\b)', '№' + NBSP, text, 'numsign-ishvh', flags=re.IGNORECASE)
    # перед № — только если непосредственно слева есть непробельный символ (буква/скобка и т.п.)
    text = _sub(r'(?<=[^\s\u00A0(«»"„“”])[ \t]+(?=№)', NBSP, text, 'numsign-before')
    return text


# ---------------------------------------------------------------------------
# 5. Дата: "20.11.2000г." / "20.11.2000 г." -> с неразрывным пробелом
#    и год: "1991 г." -> неразрывный пробел
# ---------------------------------------------------------------------------

def fix_year_god(text):
    # дата ДД.ММ.ГГГГ + г. (с пробелом или без)
    text = _sub(r'(\d{2}\.\d{2}\.\d{4})\s?г\.',
                lambda m: m.group(1) + NBSP + 'г.', text, 'date-god')
    # диапазон годов "ГГГГ гг." -> неразрывный пробел перед "гг."
    # (раньше одиночного "г.", чтобы двойное "гг." не осталось необработанным)
    text = _sub(r'(?<!\.)\b(\d{4})\s?гг\.',
                lambda m: m.group(1) + NBSP + 'гг.', text, 'years-gg')
    # просто ГГГГ г. (4 цифры года, не часть даты через точки)
    text = _sub(r'(?<!\.)\b(\d{4})\s?г\.(?!\d)',
                lambda m: m.group(1) + NBSP + 'г.', text, 'year-god')
    return text


def fix_city_g(text):
    # "г." перед словом с заглавной буквы, где перед "г." нет цифры прямо
    # (т.е. это "город", а не сокращение года). \b обязателен — иначе "Петербург."
    # ошибочно ловится по последней букве "г".
    text = _sub(r'(?<!\d)(?<!\d )\bг\.\s?(?=[А-ЯЁ])', 'г.' + NBSP, text, 'city-g')
    return text


# ---------------------------------------------------------------------------
# 6. ГрК РФ / ФЗ / Постановления / СП / ГОСТ / РМД / СанПиН
# ---------------------------------------------------------------------------

def fix_codes_refs(text):
    # ст./ч./п. NN (в статьях кодексов)
    text = _sub(r'\b(ст|ч|п)\.[ \t]*(?=\d)', lambda m: m.group(1) + '.' + NBSP, text, 'code-ref')
    # № ФЗ, № постановления — обрабатывается общим правилом fix_number_sign выше
    # СП / ГОСТ / РМД / СанПиН + номер (в т.ч. "ГОСТ Р NN.NNNN-NNNN")
    # внутренний дефис номера стандарта — это не диапазон, переводим в неразрывный дефис
    # ЗДЕСЬ (до fix_dashes), чтобы правило диапазонов его не перехватило.
    def repl_normdoc(m):
        head = m.group(1)
        r_part = m.group(2) or ''
        number = m.group(3)
        new_number = number.replace('-', NBH)
        return head + r_part.replace(' ', NBSP) + NBSP + new_number
    # допускаем, что пробел перед номером уже мог быть исправлен на nbsp ранее
    text = _sub(r'\b(СП|ГОСТ|РМД|СанПиН|СНиП|РД)([ \t\u00A0]+Р)?[ \t\u00A0]+([0-9][0-9A-Za-zА-Яа-я.\-]*\d)',
                repl_normdoc, text, 'normdoc-ref')
    return text


# ---------------------------------------------------------------------------
# 6б. Ссылочные сокращения перед числом: рис./табл./стр./прил./гл./разд./абз./пп.
#     "рис. 5" -> "рис.<nbsp>5". Требуем точку + число справа, поэтому не путается
#     с "с." = село (за ним идёт название с заглавной, а не цифра).
# ---------------------------------------------------------------------------

REF_ABBR = ['рис', 'табл', 'стр', 'прил', 'гл', 'разд', 'абз', 'пп', 'с']

def fix_ref_abbrev(text):
    # после сокращения — число ("табл. 3") ИЛИ одиночная заглавная буква-метка
    # ("табл. В", "рис. А.1", приложения/таблицы с буквенной нумерацией).
    # [А-ЯЁ]\b отсекает обычные слова ("см. табл. Ниже" — "Ниже" не одна буква).
    pat = r'\b(' + '|'.join(REF_ABBR) + r')\.[ \t]*(?=\d|[А-ЯЁ]\b)'
    text = _sub(pat, lambda m: m.group(1) + '.' + NBSP, text, 'ref-abbrev')
    return text


def fix_refnum_hyphens(text):
    # "№ 01-862/25-0-1", "письмо № 03-04/18-10571" и т.п. — номер документа после №,
    # без слова исх/вх. Внутренние дефисы такого номера — неразрывные (это не диапазон).
    def repl(m):
        return '№' + NBSP + m.group(1).replace('-', NBH)
    text = _sub(r'№\u00A0([\d][\d\-/]*\d)(?=[^\d\-/]|$)', repl, text, 'refnum-hyphen')
    return text


# ---------------------------------------------------------------------------
# 7. Сокращения улиц: ул./пр./пер./наб./пл./ш./б-р — сторона по заглавной букве
#    "пр." отдельно: если стоит после "и " — это "и пр." (и прочее), не трогаем
# ---------------------------------------------------------------------------

STREET_ABBR = r'(?:ул|пр|пер|наб|пл|ш|б-р|корп|лит|д|кв)\.'

def fix_street_abbrev(text):
    # "и пр." (и прочее) — защищаем явным правилом, применяем ДО общего "пр."
    # заменим временно на маркер, чтобы общее правило его не трогало
    PLACEHOLDER = '\x00IPR\x00'
    text = _sub(r'\bи\s?пр\.', 'и' + NBSP + 'пр.', text, 'i-pr-other')
    protected = re.sub(r'\bи' + NBSP + r'пр\.', PLACEHOLDER, text)

    # случай "ул. Название" (заглавная буква после) -> nbsp после
    def after_case(m):
        return m.group(1) + NBSP
    protected = _sub(r'\b(ул\.|пр\.|пер\.|наб\.|пл\.|ш\.|б-р\.?)[ \t]+(?=[А-ЯЁ])',
                      after_case, protected, 'street-after')

    # случай "Название ул." (слово с заглавной буквы перед сокращением) -> nbsp перед
    def before_case(m):
        return m.group(1) + NBSP + m.group(2)
    protected = _sub(r'\b([А-ЯЁ][а-яёА-ЯЁ]*)[ \t]+(ул\.|пр\.|пер\.|наб\.|пл\.|ш\.|б-р\.?)',
                      before_case, protected, 'street-before')

    text = protected.replace(PLACEHOLDER, 'и' + NBSP + 'пр.')
    return text


def fix_address_parts(text):
    # д./кв./корп. + номер; лит. + буква литеры — всегда числовой/буквенный номер справа,
    # заглавная буква тут ничего не решает (в отличие от ул./пр.)
    text = _sub(r'\b(д|кв|корп)\.[ \t]+(?=\d)', lambda m: m.group(1) + '.' + NBSP, text, 'addr-num')
    text = _sub(r'\b(литер(?:а|ы|е|у|ой|ою)?|лит\.?)[ \t]+(?=[А-ЯЁ](?:\b|\d))',
                lambda m: m.group(1) + NBSP, text, 'addr-lit')
    return text


# ---------------------------------------------------------------------------
# 7в. "участок" (во всех склонениях) + номер/№ -> неразрывный пробел:
#     "участок 27", "участка № 5", "на участке 12".
# ---------------------------------------------------------------------------

def fix_uchastok(text):
    text = _sub(r'\b(участ(?:ок|ка|ку|ком|ке|ки|ков|кам|ками|ках))[ \t]+(?=№|\d)',
                lambda m: m.group(1) + NBSP, text, 'uchastok')
    return text


# ---------------------------------------------------------------------------
# 7б. Географические сокращения перед именем собственным (заглавная буква):
#     р. Ижора, д. Аннолово, пос. Тельмана, с. Ивановское, оз. Хепоярви.
#     Отличие от адресных "д. 5" (дом+число) — здесь справа заглавная, а не цифра.
# ---------------------------------------------------------------------------

def fix_geo_abbrev(text):
    # р./оз./руч./пос./с./х./пгт + Имя (заглавная) -> неразрывный пробел
    # "ст." сюда НЕ берём: слишком неоднозначно (статья, сталь).
    text = _sub(r'\b(р|оз|руч|пос|с|х|пгт|дер)\.[ \t]*(?=[А-ЯЁ])',
                lambda m: m.group(1) + '.' + NBSP, text, 'geo-abbrev')
    # д. (деревня) + Имя (заглавная), но НЕ хвост "и т. д." / "т.д." перед новым
    # предложением с заглавной буквы.
    text = _sub(r'(?<!т\.)(?<!т\. )(?<!т\. )\bд\.[ \t]*(?=[А-ЯЁ])',
                lambda m: 'д.' + NBSP, text, 'geo-derevnya')
    return text


# ---------------------------------------------------------------------------
# 8. ЗУ / ОЗУ / ОКС / лист + № + число
# ---------------------------------------------------------------------------

def fix_zu_oks(text):
    # перед № (ЗУ №52 и т.п.)
    text = _sub(r'\b(ЗУ|ОЗУ|ОКС|лист|ИГЭ)[ \t]+(?=№)', lambda m: m.group(1) + NBSP, text, 'zu-oks-before-num')
    # напрямую перед числом, без № (лист 10, ЗУ 1, ИГЭ 3 и т.п.)
    text = _sub(r'\b(ЗУ|ОЗУ|ОКС|лист|ИГЭ)[ \t]+(?=\d)', lambda m: m.group(1) + NBSP, text, 'zu-oks-before-digit')
    return text


# ---------------------------------------------------------------------------
# 8б. Объекты энергетики/инфраструктуры + номер: ПС 5, ТП №3, БКТП 12 и т.п.
#     Длинные аббревиатуры — раньше коротких (иначе неважно: \b защищает от
#     совпадения внутри слова, напр. "ПС" внутри "ОСПС").
# ---------------------------------------------------------------------------

POWER_ABBR = r'(?:БКРТП|БКТП|ОСПС|РТП|ГРП|АТС|КЛ|ВЛ|ПС|ТП)'

def fix_power_infra(text):
    text = _sub(r'\b(' + POWER_ABBR + r')[ \t]+(?=№)', lambda m: m.group(1) + NBSP, text, 'power-before-num')
    text = _sub(r'\b(' + POWER_ABBR + r')[ \t]+(?=\d)', lambda m: m.group(1) + NBSP, text, 'power-before-digit')
    return text


# ---------------------------------------------------------------------------
# 8в. "код" (и склонения) + номер -> неразрывный пробел: "код 12.0.1".
# ---------------------------------------------------------------------------

def fix_kod(text):
    text = _sub(r'\bкод(?:а|у|ом|е)?[ \t]+(?=\d)',
                lambda m: m.group(0).rstrip() + NBSP, text, 'kod-num')
    return text


# ---------------------------------------------------------------------------
# 9. исх./вх. + номер (в т.ч. с дефисом/слэшем внутри номера -> неразрывный дефис)
# ---------------------------------------------------------------------------

def fix_ish_vh(text):
    # разделитель между исх/вх и номером — пробел или дефис — делаем неразрывным,
    # сохраняя исходный символ разделителя (не добавляем точку, если её не было).
    # Внутренние дефисы самого номера (напр. "13-13/46761") тоже переводим
    # в неразрывный дефис — это идентификатор, а не диапазон чисел.
    def repl(m):
        word, sep, number = m.group(1), m.group(2), m.group(3)
        newsep = NBH if sep == '-' else NBSP
        new_number = number.replace('-', NBH)
        return word + newsep + new_number
    text = _sub(r'\b([Ии]сх\.?|[Вв]х\.?)[ \t]*([ \t-])([\d][\d\-/]*\d)(?=[^\d\-/]|$)', repl, text, 'ish-vh')
    return text


# ---------------------------------------------------------------------------
# 10. Организационно-правовая форма + «Название» — nbsp перед кавычкой
#     и все пробелы внутри кавычек -> nbsp
# ---------------------------------------------------------------------------

FORMS = r'(?:ГУП|МУП|ООО|ОАО|ЗАО|ПАО|АО|ИП|ГБУ|ГРО|СПб\ ГКУ|ГКУ)'

def fix_org_names(text):
    def repl(m):
        form = m.group(1)
        inner = m.group(2)
        inner_nbsp = inner  # пробелы внутри кавычек оставляем обычными
        LOG.append(('org-name', m.start(), m.group(0), form + NBSP + '«' + inner_nbsp + '»'))
        return form + NBSP + '«' + inner_nbsp + '»'
    text = re.sub(r'\b(' + FORMS + r')[ \t]+«([^»]*)»', repl, text)
    return text


# ---------------------------------------------------------------------------
# 11. Связки аббревиатур: ППТ ЛО, ПЗЗ СПб, ГП СПб
# ---------------------------------------------------------------------------

def fix_abbrev_pairs(text):
    text = _sub(r'\b(ППТ|ПЗЗ|ГП)[ \t]+(ЛО|СПб)\b',
                lambda m: m.group(1) + NBSP + m.group(2), text, 'abbrev-pair')
    return text


# ---------------------------------------------------------------------------
# 12. Шифры проектов: заглавные буквы+цифры через дефис/слэш -> неразрывный дефис/слэш
# ---------------------------------------------------------------------------

def fix_project_codes(text):
    # минимум 1 буква + 1 цифра, дефис/слэш внутри, весь токен без пробелов
    pattern = r'\b(?=[A-ZА-ЯЁ0-9\-/]*[A-ZА-ЯЁ])(?=[A-ZА-ЯЁ0-9\-/]*\d)[A-ZА-ЯЁ0-9]+(?:[-/][A-ZА-ЯЁ0-9]+)+\b'
    def repl(m):
        token = m.group(0)
        new = token.replace('-', NBH).replace('/', '\u2044' if False else '/')
        # слэш неразрывным не делаем спецсимволом (word wrap на / обычно и не бывает), только дефис
        if new != token:
            LOG.append(('project-code', m.start(), token, new))
        return new
    return re.sub(pattern, repl, text)


# ---------------------------------------------------------------------------
# 13. Санкт-Петербург — неразрывный дефис / идентификаторы со слэшами
# ---------------------------------------------------------------------------

def fix_identifier_numbers(text):
    # Номер вида "78-78/006-78/006/001/2015-412/1" (рег. номера Росреестра и т.п.):
    # если в цифровом токене с дефисами есть хотя бы один слэш — это идентификатор,
    # а не диапазон чисел. Все дефисы внутри такого токена -> неразрывные.
    pattern = r'\b\d[\d\-]*/[\d\-/]*\d\b'
    def repl(m):
        token = m.group(0)
        new = token.replace('-', NBH)
        if new != token:
            LOG.append(('identifier-number', m.start(), token, new))
        return new
    return re.sub(pattern, repl, text)


def fix_spb(text):
    text = _sub(r'Санкт-Петербург', 'Санкт' + NBH + 'Петербург', text, 'spb-hyphen')
    return text


# ---------------------------------------------------------------------------
# 14. ст. NNN в.д. (сталь высокого давления)
# ---------------------------------------------------------------------------

def fix_st_vd(text):
    text = _sub(r'\bст\.[ \t]*(\d+)[ \t]*в\.\s?д\.',
                lambda m: 'ст.' + NBSP + m.group(1) + NBSP + 'в.д.', text, 'st-vd')
    return text


# ---------------------------------------------------------------------------
# 15. Инициалы + фамилия
# ---------------------------------------------------------------------------

def fix_initials(text):
    # А.Б. Иванов / А. Б. Иванов -> nbsp между инициалами и перед фамилией
    text = _sub(r'\b([А-ЯЁ])\.[ \t]?([А-ЯЁ])\.[ \t]*(?=[А-ЯЁ][а-яё])',
                lambda m: m.group(1) + '.' + NBSP + m.group(2) + '.' + NBSP, text, 'initials')
    return text


# ---------------------------------------------------------------------------
# 16. Предлоги/союзы (1-2 буквы) в начале конструкции -> nbsp со следующим словом
#     Делаем ПОСЛЕДНИМ из "пробельных" правил, т.к. остальные более специфичны.
# ---------------------------------------------------------------------------

PREPS = ['в', 'на', 'из', 'от', 'по', 'за', 'до', 'при', 'для', 'и', 'а', 'но', 'что', 'как', 'к', 'с', 'у', 'о', 'об']

def fix_prepositions(text):
    # только целые слова-предлоги, за которыми пробел и следующее слово (не знак препинания)
    pat = r'\b(' + '|'.join(PREPS) + r')[ \t]+(?=[а-яёА-ЯЁ0-9])'
    text = _sub(pat, lambda m: m.group(1) + NBSP, text, 'preposition', flags=re.IGNORECASE)
    return text


# ---------------------------------------------------------------------------
# 17. Тире: короткое в диапазонах чисел, длинное как знак препинания
# ---------------------------------------------------------------------------

def fix_dashes(text):
    # диапазон чисел: "2020-2026" -> короткое тире, без пробелов
    text = _sub(r'(?<=\d)[ \t]?-[ \t]?(?=\d)', ENDASH, text, 'range-dash')
    # длинное тире как знак препинания: пробел-дефис-пробел между словами -> em-dash, nbsp перед
    text = _sub(r'(?<=[а-яёa-z0-9А-ЯЁ\)»])[ \t]-[ \t](?=[а-яёА-ЯЁa-z0-9«])',
                lambda m: NBSP + EMDASH + ' ', text, 'em-dash')
    # перед УЖЕ имеющимся тире (— или –) как знаком препинания обычный пробел -> nbsp
    # (чтобы тире не оказалось в начале строки); после тире пробел остаётся обычным.
    text = _sub(r'(?<=[а-яёa-z0-9А-ЯЁ\)»])[ \t]+(?=[\u2014\u2013][ \t\u00A0])',
                NBSP, text, 'dash-nbsp-before')
    return text


# ---------------------------------------------------------------------------
# 18. Кавычки: прямые "..." -> ёлочки «...»
# ---------------------------------------------------------------------------

def fix_quotes(text):
    def repl(m):
        return '«' + m.group(1) + '»'
    text = _sub(r'"([^"\n]+)"', repl, text, 'straight-quotes')
    return text


# ---------------------------------------------------------------------------
# 19. Пробелы: множественные -> один, убрать перед знаками препинания
# ---------------------------------------------------------------------------

def fix_spaces(text):
    text = _sub(r'[ \t]{2,}', ' ', text, 'multi-space')
    text = _sub(r'[ \t]+([.,;:!?])', r'\1', text, 'space-before-punct')
    return text


