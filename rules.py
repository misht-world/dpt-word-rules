def fix_ref_words(text):
    """приложение/примечание/таблица (в склонениях) + число ИЛИ одиночная
    заглавная буква-метка -> неразрывный пробел: «таблица 8.13», «приложение М».
    [А-ЯЁ]\b отсекает обычные слова («приложение Настоящего» не трогаем)."""
    text = _sub(r'\b(?:приложени|примечани|таблиц)[а-яё]{1,3}[ \t]+(?=\d|[А-ЯЁ]\b)',
                lambda m: m.group(0).rstrip() + NBSP, text, 'ref-word')
    return text


_SCALE = r'(?:тыс\.|тысяч\w*|млн\.?|млрд\.?|миллион\w*|миллиард\w*)'
_CURR = r'(?:руб\.|рубл\w*|коп\.|копе\w*|\u20bd)'

def fix_money(text):
    """Денежные суммы: число+масштаб (тыс./млн/млрд/тысяч) и масштаб/число+валюта
    (руб./рубль/коп./₽) -> неразрывный пробел. «200 тысяч рублей» -> все nbsp."""
    text = _sub(r'(\d)[ \t]+(?=' + _SCALE + r')', lambda m: m.group(1) + NBSP, text, 'money-scale')
    text = _sub(r'(' + _SCALE + r'|\d)[ \t]+(?=' + _CURR + r')', lambda m: m.group(1) + NBSP, text, 'money-curr')
    return text


def fix_digit_groups(text):
    """Разряды больших чисел: пробел-разделитель тысяч делаем неразрывным.
    "1 222,5" -> "1<nbsp>222,5"; "1 234 567" -> все внутренние пробелы nbsp.
    Требуется 1-3 ведущие цифры + группы РОВНО по 3 (иначе это не разряды),
    поэтому годы "2020 2021" и т.п. не задеваются."""
    text = _sub(r'(?<!\d)\d{1,3}(?:[ \t]\d{3})+(?:[.,]\d+)?(?!\d)',
                lambda m: m.group(0).replace(' ', NBSP).replace('\t', NBSP),
                text, 'digit-groups')
    return text


def fix_org_inner_clean(text):
    """Финальный проход: внутри кавычек орг-названий убираем неразрывные ПРОБЕЛЫ
    (которые мог добавить fix_prepositions, напр. после «и»), возвращая обычные.
    Неразрывный дефис (Санкт-Петербург) не трогаем. Между формой и « — nbsp."""
    def repl(m):
        form, inner = m.group(1), m.group(2)
        return form + NBSP + '«' + inner.replace(NBSP, ' ') + '»'
    return re.sub(r'\b(' + FORMS + r')[ \t\u00A0]+«([^»]*)»', repl, text)


